'use strict';
// Deterministic tests for certificate PDF validation/path scoping plus wiring checks.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'app.js'), 'utf8');
const start = source.indexOf('  const CERT_LIMIT_BYTES = 10 * 1024 * 1024;');
const end = source.indexOf('  function certificateDateISO(raw){', start);
assert.ok(start >= 0 && end > start, 'Certificate file helpers should exist');
const helperSource = source.slice(start, end) + '\nthis.validateCertificatePDF=validateCertificatePDF; this.certificateAttachmentPath=certificateAttachmentPath;';
const context = {};
vm.runInNewContext(helperSource, context);
assert.equal(context.validateCertificatePDF(null), 'Select the original certificate PDF before saving.');
assert.equal(context.validateCertificatePDF({name:'blank.pdf',size:0}), 'The selected PDF is empty or unreadable.');
assert.equal(context.validateCertificatePDF({name:'oversize.pdf',size:10*1024*1024+1}), 'PDF exceeds 10 MB. Reduce the file size and retry.');
assert.equal(context.validateCertificatePDF({name:'report.docx',size:10}), 'Select a PDF file.');
assert.equal(context.validateCertificatePDF({name:'certificate.PDF',size:1024}), '');
assert.equal(context.certificateAttachmentPath('org-uuid','user-uuid','third party certificate (2026).pdf','fixed-token'), 'org-uuid/user-uuid/fixed-token-third_party_certificate__2026_.pdf');
assert.throws(() => context.certificateAttachmentPath('', 'user-uuid', 'doc.pdf', 'fixed-token'), /active company/);
assert.throws(() => context.certificateAttachmentPath('org-uuid', '', 'doc.pdf', 'fixed-token'), /active company/);
assert.throws(() => context.certificateAttachmentPath('org-uuid', 'user-uuid', 'doc.pdf', ''), /active company/);
assert.match(source, /sb\.storage\.from\('hse-attachments'\)\.upload\(uploadedPath,certificateSourceFile/);
assert.match(source, /p_attachment:attachment/);
assert.match(source, /sb\.storage\.from\('hse-attachments'\)\.remove\(\[uploadedPath\]\)/, 'Failed record save should attempt to clean up its uploaded file');
assert.match(source, /Record now owns the attachment/);
assert.match(source, /original PDF is stored in private company attachment storage and linked to the certificate record/);
assert.match(source, /function resetCertificateReview\(\)\{certificateSourceName='';certificateSourceFile=null/);
const sql = fs.readFileSync(path.join(root, 'supabase/v8-multitenant.sql'), 'utf8');
assert.match(sql, /values\('hse-attachments','hse-attachments',false\)/, 'Attachment bucket must remain private');
assert.match(sql, /storage\.foldername\(name\)\)\[1\]::uuid\)/, 'Storage access must be organization scoped');
console.log('CERTIFICATE ATTACHMENT WORKFLOW: PASSED (18 assertions)');
