'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const sql = fs.readFileSync(path.join(root, 'supabase/v8.8.4-certificate-duplicate-guard.sql'), 'utf8');
assert.match(sql, /begin;[\s\S]*commit;/i, 'Migration should be transactional');
assert.match(sql, /public\.hse_records/);
assert.match(sql, /r\.module\s*=\s*'licenses'/i);
assert.equal((sql.match(/create unique index if not exists/gi)||[]).length, 2, 'Both certificate-key variants need unique indexes');
assert.match(sql, /hse_records_licenses_doc_no_issuer_expiry_uniq/);
assert.match(sql, /hse_records_licenses_title_issuer_expiry_uniq/);
assert.match(sql, /organization_id[\s\S]*document_no[\s\S]*authority[\s\S]*expiry_date/i, 'Keys should include tenant, issuer/number and expiry');
assert.match(sql, /HAVING count\(\*\) > 1[\s\S]*RAISE EXCEPTION/i, 'Existing duplicates should stop migration instead of deleting history');
assert.match(sql, /Different expiry[\s\S]*valid/i, 'Migration should document that expiry changes can represent renewals');
assert.match(sql, /WHERE module = 'licenses'/i);
assert.match(sql, /lower\(regexp_replace/);
assert.match(sql, /nullif\(r\.data->>'document_name',''\),r\.summary/);
assert.match(sql, /ISSUED:/, 'Certificates without expiry should use issue date as the identity fallback');
assert.match(sql, /END;\s*\$preflight\$;/, 'DO block must terminate correctly');
console.log('CERTIFICATE DUPLICATE SQL STATIC SMOKE: PASSED (13 assertions)');
