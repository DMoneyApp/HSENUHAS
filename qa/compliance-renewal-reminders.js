'use strict';
// Deterministic tests for compliance expiry windows and active/completed record treatment.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'app.js'), 'utf8');
const start = source.indexOf('  function complianceDaysRemaining(');
const end = source.indexOf('  function expiryItems(){', start);
assert.ok(start >= 0 && end > start, 'Compliance reminder helper functions should exist');
const context = {};
vm.runInNewContext(source.slice(start, end) + '\nthis.complianceDaysRemaining=complianceDaysRemaining; this.complianceRenewalBand=complianceRenewalBand; this.complianceRecordNeedsAlert=complianceRecordNeedsAlert;', context);
const day = (date) => context.complianceDaysRemaining(date, '2026-10-12');
assert.equal(day('2026-10-12'), 0, 'Expiry today is day zero');
assert.equal(day('2026-10-19'), 7);
assert.equal(day('2026-10-20'), 8);
assert.equal(day('2026-11-11'), 30);
assert.equal(day('2026-11-12'), 31);
assert.equal(day('2026-12-11'), 60);
assert.equal(day('2026-12-12'), 61);
assert.equal(day('2027-01-10'), 90);
assert.equal(day('2027-01-11'), 91);
assert.equal(day('2026-10-11'), -1, 'Past expiry should be overdue');
assert.equal(context.complianceDaysRemaining('2026-02-30', '2026-02-01'), null, 'Impossible calendar dates should not be trusted');
assert.equal(context.complianceDaysRemaining('12/31/2026', '2026-10-12'), null, 'Non-ISO date strings should be flagged for correction');
assert.equal(context.complianceDaysRemaining('2024-03-01', '2024-02-28'), 2, 'UTC arithmetic should survive leap years');
assert.equal(context.complianceRenewalBand(-1), 'Expired / overdue');
assert.equal(context.complianceRenewalBand(0), 'Expires today');
assert.equal(context.complianceRenewalBand(7), 'Due within 7 days');
assert.equal(context.complianceRenewalBand(30), 'Due within 30 days');
assert.equal(context.complianceRenewalBand(60), 'Due within 60 days');
assert.equal(context.complianceRenewalBand(90), 'Due within 90 days');
assert.equal(context.complianceRenewalBand(91), 'Outside reminder window');
assert.equal(context.complianceRenewalBand(null), 'Invalid expiry date');
assert.equal(context.complianceRecordNeedsAlert({data:{renewal_status:'Valid'}}, 30), true, 'Valid certificates still need upcoming renewal alerts');
assert.equal(context.complianceRecordNeedsAlert({data:{compliance_status:'Compliant'}}, 7), true, 'Compliant records still need time-based renewal alerts');
assert.equal(context.complianceRecordNeedsAlert({data:{renewal_status:'Closed'}}, 10), false, 'Closed compliance records should not alert');
assert.equal(context.complianceRecordNeedsAlert({data:{renewal_status:'Renewed'}}, -4), false, 'Explicitly renewed records should not keep alerting');
assert.equal(context.complianceRecordNeedsAlert({data:{renewal_status:'Valid'}}, null), true, 'Invalid nonblank expiry dates should surface for correction');
assert.match(source, /complianceRenewalBand\(daysRemaining\)/);
assert.match(source, /certificateIsSuperseded\(r,state\.records\)/);
assert.match(source, /Expiry alerts at 90 \/ 60 \/ 30 \/ 7 days/);
assert.match(source, /Expires today/);
assert.match(source, /Owner not assigned/);
assert.match(source, /invalid expiry date/i);
console.log('COMPLIANCE RENEWAL REMINDERS: PASSED (27 assertions)');
